package com.demo.numberSeries;

public class Demo1 {
	
	public static void main(String[] args) {
		
		//find the evene number from  1 to n
		
		for (int i =1;i<=20;i++) {
			
			if (i %2 == 0) {
				System.out.println("even number :"+i);
			}
			else {
				System.out.println("odd number :"+i);
			}
			
		}
	}

}
